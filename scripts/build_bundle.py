#!/usr/bin/env python3
"""
Bundle all frozen layers into a single data/bundle.js assigning globals, so the
page works from file:// by double-click (fetch() of local files is CORS-blocked
in Chromium; <script src> is not).

Usage: python3 -I scripts/build_bundle.py <data_dir> <out_js>
"""
import json, os, sys

# Legacy layers (kept for retro-compatibility with the v0 index.html).
LAYERS = [
    ("SD_ADM0", "boundaries/sudan_adm0.geojson"),
    ("SD_ADM1", "boundaries/sudan_adm1.geojson"),
    ("SD_CLASHES", "events_clashes.geojson"),
    ("SD_FIRMS", "firms_grid.geojson"),
    ("SD_ACTIVITY", "activity_grid.geojson"),
    ("SD_CIV", "civilian_violence_by_state.json"),
    ("SD_SUMMARY", "ucdp_summary.json"),
]

# Enriched, normalized contract consumed by the architect UI (see data/SCHEMA.md).
SUDAN_CORE = "sudan_core.json"


def main(data_dir, out_js):
    parts = ["/* Auto-generated by scripts/build_bundle.py. Frozen local data. */"]
    # 1) legacy window.SD_* globals (additive, do not remove)
    for var, rel in LAYERS:
        p = os.path.join(data_dir, rel)
        with open(p, encoding="utf-8") as f:
            obj = json.load(f)
        parts.append(f"window.{var} = " + json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + ";")
    # 2) enriched window.SUDAN contract object
    core_path = os.path.join(data_dir, SUDAN_CORE)
    with open(core_path, encoding="utf-8") as f:
        sudan = json.load(f)
    parts.append("window.SUDAN = " + json.dumps(sudan, ensure_ascii=False, separators=(",", ":")) + ";")
    with open(out_js, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")
    print("wrote", out_js, os.path.getsize(out_js), "bytes",
          "| SUDAN keys:", ",".join(sudan.keys()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
